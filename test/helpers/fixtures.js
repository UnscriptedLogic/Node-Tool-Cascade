'use strict';
// The "secrets" below are made up and are put together at run time, so no key-shaped text sits in the repo
// for a secret scanner to trip over.
const FAKE_KEY = ['sk','abcdefghijklmnopqrstuvwx1234567890'].join('-');
const FAKE_ENV_KEY = ['sk','should','never','be','read','1234567890'].join('-');
const FAKE_PEM = ['-----BEGIN','PRIVATE','KEY-----'].join(' ');
// Tiny game projects written to a temp folder, shaped like real ones.
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');

function write(root,rel,text){ const f = path.join(root,rel); fs.mkdirSync(path.dirname(f),{ recursive:true }); fs.writeFileSync(f,text); }

function makeUnity(){
  const root = fs.mkdtempSync(path.join(os.tmpdir(),'cascade-unity-'));
  write(root,'ProjectSettings/ProjectVersion.txt','m_EditorVersion: 2022.3.1f1');
  write(root,'Assets/Scripts/Player/PlayerController.cs',`// Handles walking, sprinting and jumping for the explorer.
// Keep travel slow and deliberate: the game is about noticing things.
using UnityEngine;
public class PlayerController : MonoBehaviour {
  public float moveSpeed = 6.5f;
  public float sprintMultiplier = 1.6f;
  public float jumpForce = 12f;
  public float stamina = 100f;
  // TODO: should there be a double jump? Design hasn't decided.
  void Update() { Move(); }
  void Move() { /* walk */ }
  public void Jump() { }
}
`);
  write(root,'Assets/Scripts/Enemies/EnemyAI.cs',`public class EnemyAI {
  public float attackRange = 2.5f;
  public float windUpTime = 0.3f;   // FIXME: too short to read, players get hit without warning
  enum State { Idle, Chase, Attack }
}
`);
  write(root,'Assets/Scripts/World/MapGenerator.cs',`public class MapGenerator {
  public int mapWidth = 128;
  public int mapHeight = 128;
  public int landmarkSpacing = 40;
  void Generate() { }
}
`);
  write(root,'Assets/Scripts/Net/Online.cs',`public class Online { string apiKey = "${FAKE_KEY}"; string password = "hunter2hunter2"; }`);
  write(root,'Assets/Scripts/Generated/Auto.cs','// <auto-generated>\npublic class Auto { }');
  write(root,'Assets/Scripts/Tmp/Scratch.cs','public class Scratch { }');
  write(root,'Assets/Plugins/Lib/ThirdParty.cs','public class ThirdParty { }');
  write(root,'Library/Cache/cached.cs','public class Cached { }');
  write(root,'Assets/Art/hero.png','\u0000PNG');
  write(root,'Assets/Scenes/Main.unity','%YAML 1.1');
  write(root,'Assets/Scripts/blob.cs','x'.repeat(300*1024));
  write(root,'Assets/Scripts/min.js','a;'.repeat(2000));
  write(root,'docs/DESIGN.md',`# Pillars\nExploration should feel like discovery, not a commute.\nNo fast travel in the first act.\n## Open questions\nTBD: how big is the world?\n`);
  write(root,'.env',`API_KEY=${FAKE_ENV_KEY}`);
  write(root,'config/keys.pem',`${FAKE_PEM}\nabc\n${FAKE_PEM.replace('BEGIN','END')}`);
  write(root,'.gitignore','Assets/Scripts/Tmp/\n*.txt\n!keep.txt\n');
  write(root,'scratch.txt','noise'); write(root,'keep.txt','kept');
  return root;
}
module.exports = { write, makeUnity, FAKE_KEY, FAKE_ENV_KEY };
