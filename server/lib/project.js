function expandHome(p){ return p.startsWith('~') ? path.join(require('os').homedir(),p.slice(1)) : p; }
function isUnsafeRoot(real){
  const parsed = path.parse(real);
  if(real===parsed.root) return true;                      // "/" or "C:\"
  const home = require('os').homedir();
  if(real===home) return true;                             // the whole home folder
  return false;
}

async function resolveRoot(rawPath){
  let root;
  try{ root = await fsp.realpath(path.resolve(expandHome(String(rawPath||'').trim()))); }
  catch(e){ throw new HttpError(400,'That folder doesn’t exist.'); }
  const st = await fsp.stat(root).catch(()=>null);
  if(!st || !st.isDirectory()) throw new HttpError(400,'That path isn’t a folder.');
  if(isUnsafeRoot(root)) throw new HttpError(400,'That’s too broad. Choose the project’s own folder, not a drive root or your whole home folder.');
  return root;
}
