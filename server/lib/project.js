function lineSymbol(line){
  let m;
  if((m = line.match(SYMBOL[0]))) return { kind:m[1], name:m[2] };
  if((m = line.match(SYMBOL[1]))) return { kind:'class', name:m[1] };
  if((m = line.match(SYMBOL[2]))) return { kind:'function', name:m[2] };
  if((m = line.match(SYMBOL[3]))) return { kind:'signal', name:m[1] };
  if((m = line.match(SYMBOL[4])) && !/^\s*(if|for|while|switch|return|else)\b/.test(line)) return { kind:'function', name:m[1] };
  if(NOT_A_DECL.test(line)) return null;
  if((m = line.match(CPP_QUALIFIED))) return { kind:'function', name:m[1] };
  // a function with no access modifier, as Unity and C++ code usually has: `void Move() {` or `float Speed(int x)`
  if((m = line.match(LOOSE_FN)) && !KEYWORDS.has(m[1])) return { kind:'function', name:m[1] };
  return null;
}
