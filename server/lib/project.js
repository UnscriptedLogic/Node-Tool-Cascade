// Replaces anything that looks like a key, token or private key. The password pattern keeps its quotes.
function redactFull(text){
  let n = 0;
  for(const [re,rep] of SECRET_RES){
    text = text.replace(re,(...m)=>{ n++; if(typeof rep==='string' && rep.includes('$1')) return rep.replace('$1',m[1]).replace(/\$2/g,m[2]); return rep; });
  }
  return { text, count:n };
}

