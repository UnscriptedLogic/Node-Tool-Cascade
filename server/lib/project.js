// A small, faithful-enough implementation: comments, negation, anchoring, directory-only, *, **, ?, [] and nesting.
function globToRegex(glob){
  let re = '', i = 0;
  while(i<glob.length){
    const c = glob[i];
    if(c==='*'){
      if(glob[i+1]==='*'){
        const prev = glob[i-1], next = glob[i+2];
        if((prev===undefined || prev==='/') && next==='/'){ re += '(?:.*/)?'; i += 3; continue; }
        re += '.*'; i += 2; continue;
      }
      re += '[^/]*'; i++; continue;
    }
    if(c==='?'){ re += '[^/]'; i++; continue; }
    if(c==='['){
      const j = glob.indexOf(']',i+2);
      if(j>0){ re += '['+glob.slice(i+1,j).replace(/^!/,'^').replace(/\\/g,'\\\\')+']'; i = j+1; continue; }
    }
    if(c==='\\' && i+1<glob.length){ re += glob[i+1].replace(/[.*+?^${}()|[\]\\]/g,'\\$&'); i += 2; continue; }
    re += c.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'); i++;
  }
  return re;
}
function parseIgnore(text,baseDir){
  const rules = [];
  for(let line of String(text).split(/\r?\n/)){
    line = line.replace(/\s+$/,'');
    if(!line || line.startsWith('#')) continue;
    let neg = false;
    if(line.startsWith('!')){ neg = true; line = line.slice(1); }
    if(line.startsWith('\\#') || line.startsWith('\\!')) line = line.slice(1);
    let dirOnly = false;
    if(line.endsWith('/')){ dirOnly = true; line = line.slice(0,-1); }
    if(!line) continue;
    const anchored = line.includes('/');
    if(line.startsWith('/')) line = line.slice(1);
    const body = globToRegex(line);
    const re = new RegExp('^'+(anchored ? '' : '(?:.*/)?')+body+'$');
    rules.push({ re, neg, dirOnly, base:baseDir });
  }
  return rules;
}
// rules: ordered list; the last matching rule wins. rel is a posix path relative to the project root.
function ignored(rules,rel,isDir){
  let result = false;
  for(const r of rules){
    if(r.dirOnly && !isDir) continue;
    let sub = rel;
    if(r.base){ if(!rel.startsWith(r.base+'/')) continue; sub = rel.slice(r.base.length+1); }
    if(r.re.test(sub)) result = !r.neg;
  }
  return result;
}

