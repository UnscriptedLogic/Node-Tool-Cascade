function saveBrief(b){
  const m = meta(); if(!m) throw new HttpError(400,'Scan a project first.');
  if(typeof b.brief==='string') m.brief = b.brief.slice(0,12000);
  if(b.briefMeta && typeof b.briefMeta==='object') m.briefMeta = { at:Date.now(), model:String(b.briefMeta.model||'').slice(0,80), groups:+b.briefMeta.groups||0, edited:!!b.briefMeta.edited };
  if(Array.isArray(b.findings)) m.findings = b.findings.slice(0,600).map(x=>({
    id:String(x.id||'').slice(0,12), kind:['mechanic','parameter','state','decision','open','constraint','system'].includes(x.kind)?x.kind:'system',
    text:String(x.text||'').trim().slice(0,260), group:String(x.group||'').slice(0,60),
    refs:(Array.isArray(x.refs)?x.refs:[]).slice(0,3).map(r=>({ file:String(r.file||'').slice(0,300), line:Math.max(1,+r.line||1) }))
  })).filter(x=>x.text);
  if(b.groupFindings && typeof b.groupFindings==='object'){
    const gf = {}; for(const [k,v] of Object.entries(b.groupFindings).slice(0,80)) gf[String(k).slice(0,24)] = String(v).slice(0,40);
    m.groupFindings = gf;
  }
  saveMeta(m); return publicInfo();
}
