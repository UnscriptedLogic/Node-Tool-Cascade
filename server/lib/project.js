function search(q,k=6,opts={}){
  if(!state || !state.chunks.length) return [];
  const terms = [...new Set(tokenize(q))]; if(!terms.length) return [];
  const { df, avg, n } = state.bm25, k1 = 1.4, b = .72, out = [];
  for(const c of state.chunks){
    let score = 0;
    for(const t of terms){
      const f = c.tf.get(t); if(!f) continue;
      const idf = Math.log(1+(n-(df.get(t)||0)+.5)/((df.get(t)||0)+.5));
      score += idf*(f*(k1+1))/(f+k1*(1-b+b*c.len/avg));
    }
    if(score<=0) continue;
    if(DOC_EXT.has(path.extname(c.file).toLowerCase())) score *= 1.15;   // intent beats implementation when both match
    if(c.sym && terms.some(t=>tokenize(c.sym).includes(t))) score *= 1.2;
    out.push({ c, score });
  }
  out.sort((a,b2)=>b2.score-a.score);
  // at most two chunks per file so one big file cannot crowd out the rest
  const per = new Map(), picked = [];
  for(const r of out){
    const n2 = per.get(r.c.file)||0; if(n2>=(opts.perFile||2)) continue;
    per.set(r.c.file,n2+1); picked.push({ file:r.c.file, start:r.c.start, end:r.c.end, text:r.c.text, score:Math.round(r.score*100)/100, sym:r.c.sym||'' });
    if(picked.length>=k) break;
  }
  return picked;
}

