function digestFile(rel,text,ext){
  const lines = text.split('\n');
  const symbols = [], tunables = [], todos = [];
  let header = '';
  // header comment or docstring: the first comment block in the first 40 lines
  const head = [];
  for(let i=0;i<Math.min(lines.length,40);i++){
    const l = lines[i];
    if(COMMENT_START.test(l) || /^\s*("""|''')/.test(l)) head.push(l.replace(/^\s*(\/\/+|#+|--+|\/\*+|\*+\/?|;+|"""|''')\s?/,'').trim());
    else if(head.length && l.trim()==='') break;
    else if(head.length) break;
  }
  header = head.filter(Boolean).join(' ').slice(0,400);
  for(let i=0;i<lines.length;i++){
    const l = lines[i];
    const sym = lineSymbol(l);
    if(sym && symbols.length<60) symbols.push({ line:i+1, kind:sym.kind, name:sym.name });
    const t = l.match(TODO_RE);
    if(t && todos.length<25 && (COMMENT_START.test(l) || /\/\/|#|--/.test(l))) todos.push({ line:i+1, text:(t[1].toUpperCase()+': '+t[2]).trim().slice(0,160) });
    if(CODE_EXT.has(ext) || ext==='.json' || ext==='.ini' || ext==='.cfg' || ext==='.tres' || ext==='.yaml' || ext==='.yml' || ext==='.toml'){
      const n = l.match(NUM_ASSIGN);
      if(n && TUNABLE.test(n[1]) && tunables.length<40 && !/^\s*(\/\/|#|\*)/.test(l)) tunables.push({ line:i+1, name:n[1], value:n[2] });
    }
  }
  return { symbols, tunables, todos, header };
}

/* --------------------------- design relevance, to decide what to read first --------------------------- */
const DESIGN_WORDS = /(player|character|hero|enemy|boss|npc|ability|skill|spell|combat|battle|attack|weapon|damage|health|inventory|item|loot|quest|dialog|dialogue|story|level|world|map|zone|biome|spawn|wave|camera|input|control|movement|move|jump|traverse|travel|stamina|upgrade|progress|economy|shop|crafting|save|checkpoint|game|manager|state|machine|ai|behaviou?r|rule|config|setting|balance|tuning|data|design|gdd|readme|notes|todo|roadmap)/i;
const DEMOTE = /(test|tests|spec|mock|editor|tools?|debug|example|sample|demo|migration|generated|\.min\.|vendor|thirdparty|third_party|plugin|stub)/i;
function relevance(rel,ext,digest,size){
  let s = 0;
  const base = path.basename(rel);
  if(DOC_EXT.has(ext)) s += 6;
  if(/^readme/i.test(base) || /(design|gdd|roadmap|notes|spec)/i.test(base)) s += 6;
  if(DESIGN_WORDS.test(rel)) s += 3;
  if(DEMOTE.test(rel)) s -= 4;
  s += Math.min(6,digest.todos.length*1.5);
  s += Math.min(5,digest.tunables.length*.5);
  s += Math.min(3,digest.symbols.length*.1);
  if(size<400) s -= 3;
  if(size>120*1024) s -= 2;
  return Math.round(s*10)/10;
}

/* ----------------------------------- chunking + search ----------------------------------- */
function chunkText(text){
  const lines = text.split('\n'), out = [];
  let i = 0;
  while(i<lines.length){
    let end = Math.min(lines.length,i+LIMITS.chunkLines), body = lines.slice(i,end).join('\n');
    while(body.length>LIMITS.chunkMaxChars && end-i>8){ end--; body = lines.slice(i,end).join('\n'); }
    if(body.trim()) out.push({ start:i+1, end, text:body });
    if(end>=lines.length) break;
    i = Math.max(i+1,end-LIMITS.chunkOverlap);
  }
  return out;
}
